export const clubNames: Record<string, string> = {
  wine: "ワイン部",
  coffee: "コーヒー部",
  travel: "旅部",
};

export function getReports(clubId: string): ClubReport[] {
  return allReports[clubId] ?? allReports.wine;
}

export function getReport(clubId: string, reportId: number): ClubReport | undefined {
  return getReports(clubId).find(r => r.id === reportId);
}

export function getClubName(clubId: string): string {
  return clubNames[clubId] ?? "クラブ";
}
